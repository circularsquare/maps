import {writeFile} from 'node:fs/promises';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE??'playwright');
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
try{
 const page=await browser.newPage({viewport:{width:688,height:953}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:8800/trainworld/?debug=1&new=1&paused=1');
 await page.waitForFunction(()=>window.tw?.world.value&&window.tw.overlay.camMatrix);
 await page.evaluate(async()=>{
  const tw=window.tw,a=await tw.client.edit({op:'route',from:{kind:'free',x:0,y:0,level:-2},to:{kind:'free',x:4000,y:0,level:-2},pis:[],single:false});
  if(!a.ok)throw Error(JSON.stringify(a));window.edge=tw.world.value.edges[0].id;tw.select({kind:'track',edge:window.edge});
  document.querySelector('#debug').style.display='none';
 });
 const shape=()=>page.evaluate(async()=>Array.from(await window.tw.client.query({what:'edgePis',edge:window.edge})));
 const waitCorners=async count=>{await page.waitForFunction(count=>document.querySelectorAll('.corner').length===count,count);await page.waitForTimeout(50);};
 await page.getByRole('button',{name:'Add corner',exact:true}).click();await waitCorners(1);
 const added=await shape();if(added.length!==9||added[1]!==2000||added[4]!==-2)throw Error('Midpoint corner not added '+added);
 const beforeDrag=await page.evaluate(()=>window.tw.world.value.version);
 const mark=await page.locator('.pi-mark.drag').boundingBox();
 await page.mouse.move(mark.x+mark.width/2,mark.y+mark.height/2);await page.mouse.down();
 await page.mouse.move(mark.x+mark.width/2,mark.y+mark.height/2-60,{steps:10});await page.mouse.up();
 await page.waitForFunction(v=>window.tw.world.value.version>v,beforeDrag);
 const dragged=await shape();if(Math.abs(dragged[2])<100||dragged[5]<=0)throw Error('New corner not draggable '+dragged);
 await page.getByRole('button',{name:'More corner 1 level',exact:true}).click();await waitCorners(1);
 await page.waitForFunction(()=>window.tw.world.value.edges[0].levelMax===-1);
 const raised=await shape();if(raised[4]!==-1)throw Error('Individual corner level not changed');
 await page.getByRole('button',{name:'Add corner 2',exact:true}).click();await waitCorners(2);
 const two=await shape();if(two.length!==17||Math.abs(two[9]-(raised[1]+4000)/2)>.1)throw Error('Corner order not preserved '+two);
 await page.getByRole('button',{name:'Remove corner 1',exact:true}).click();await waitCorners(1);
 const removed=await shape();if(removed[1]!==two[9])throw Error('Wrong corner removed');
 await page.evaluate(()=>window.tw.client.edit({op:'undo'}));await waitCorners(2);
 const undone=await shape();if(JSON.stringify(undone)!==JSON.stringify(two))throw Error('Undo did not restore exact shape');
 await page.evaluate(()=>window.tw.client.edit({op:'redo'}));await waitCorners(1);
 if(JSON.stringify(await shape())!==JSON.stringify(removed))throw Error('Redo did not restore removal');
 const layout=await page.locator('#inspector').evaluate(e=>({width:e.clientWidth,scrollWidth:e.scrollWidth}));
 if(layout.scrollWidth>layout.width+1)throw Error('Corner controls overflow narrow inspector');
 await page.locator('.corner').scrollIntoViewIfNeeded();await page.screenshot({path:'artifacts/trainworld/T-071-corners.png'});
 await page.getByRole('button',{name:'Remove corner 1',exact:true}).click();await waitCorners(0);
 if((await shape()).length!==1)throw Error('Removing last corner should restore straight track');
 await page.evaluate(()=>window.tw.client.edit({op:'construct',edges:[window.edge],stations:[]}));
 await page.waitForFunction(()=>window.tw.world.value.edges[0].built);
 if(await page.getByRole('button',{name:/Add corner/}).count())throw Error('Constructed track exposes shape editing');
 const refusal=await page.evaluate(()=>window.tw.client.edit({op:'edgePis',edge:window.edge,pis:[{x:2000,y:1000,level:0,radius:0}]}));
 if(refusal.ok)throw Error('Constructed edge was reshaped');
 if(errors.length)throw Error(errors.join('\n'));
 const result={added,dragged,raised,two,removed,layout,refusal,errors};console.log(JSON.stringify(result));await writeFile('artifacts/trainworld/notes-outputs/T-071-check.json',JSON.stringify(result,null,2));
}finally{await browser.close();}
